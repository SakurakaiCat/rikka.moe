export const escapeHtml = (value: unknown) => String(value ?? '')
  .replace(/&/g, '&')
  .replace(/</g, '<')
  .replace(/>/g, '>')
  .replace(/"/g, '"')
  .replace(/'/g, '&#039;');

export function renderTocHtml(toc: TocPart[]) {
  return toc.map((part, partIndex) => `
    <details class="akari-book-toc__part" ${partIndex === 0 ? 'open' : ''}>
      <summary>
        <span class="akari-book-toc__label">${escapeHtml(part.label)}</span>
        <strong>${escapeHtml(part.title)}</strong>
        <i class="ph ph-caret-down"></i>
      </summary>
      <div class="akari-book-toc__children">
        ${part.children.map((child) => `
          <div class="akari-book-toc__child">
            <div class="akari-book-toc__child-head">
              <span>${escapeHtml(child.label)}</span>
              <strong>${escapeHtml(child.title)}</strong>
            </div>
            ${child.sub && child.sub.length > 0 ? `
              <ul class="akari-book-toc__sub">
                ${child.sub.map((sub, index) => `<li><span>${String(index + 1).padStart(2, '0')}</span>${escapeHtml(sub)}</li>`).join('')}
              </ul>
            ` : ''}
          </div>
        `).join('')}
      </div>
    </details>
  `).join('');
}

export function renderErrataTier(label: string, title: string, items: string[], defaultOpen = false) {
  const listItems = items.map(item => '<li>' + item + '</li>').join('');
  return '<details class="akari-errata-tier"' + (defaultOpen ? ' open' : '') + '>'
    + '<summary><span class="akari-errata-tier__label">' + label + '</span><strong>' + title + '</strong><span class="akari-errata-tier__count">' + items.length + ' 项</span><i class="ph ph-caret-down"></i></summary>'
    + '<ol class="akari-errata-tier__list">' + listItems + '</ol></details>';
}
